-- H2 SQL schema definition

-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(30) UNIQUE NOT NULL CHECK (length(username) BETWEEN 3 AND 30 AND username REGEXP '^[A-Za-z0-9_]+$'),
    password_hash VARCHAR(255) NOT NULL,
    recovery_key_hash VARCHAR(64) NOT NULL,
    is_admin BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Lists Table
CREATE TABLE IF NOT EXISTS lists (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                       title VARCHAR(255) NOT NULL,
                       is_deleted BOOLEAN DEFAULT FALSE NOT NULL,
                       deleted_at TIMESTAMP WITH TIME ZONE NULL,
                       created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Index for performance on active lists and archive queries
CREATE INDEX IF NOT EXISTS idx_lists_owner_deleted ON lists(owner_id, is_deleted);

-- 3. List Shares Table (Permissions: Editor / Viewer)
CREATE TABLE IF NOT EXISTS list_shares (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             list_id BIGINT NOT NULL REFERENCES lists(id) ON DELETE CASCADE,
                             user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                             permission VARCHAR(20) NOT NULL CHECK (permission IN ('editor', 'viewer')),
                             created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
                             UNIQUE (list_id, user_id)
);

-- Index for quick lookup in the "Megosztva velem" (Shared with me) view
CREATE INDEX IF NOT EXISTS idx_list_shares_user ON list_shares(user_id);

-- 4. Items Table (Shopping List Items)
CREATE TABLE IF NOT EXISTS items (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       list_id BIGINT NOT NULL REFERENCES lists(id) ON DELETE CASCADE,
                       name VARCHAR(255) NOT NULL CHECK (length(trim(name)) > 0),
                       quantity DECIMAL(10, 2) NOT NULL CHECK (quantity > 0),
                       unit VARCHAR(50) NOT NULL,
                       is_checked BOOLEAN DEFAULT FALSE NOT NULL,
                       created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
                       created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Index for fast retrieval of items per list
CREATE INDEX IF NOT EXISTS idx_items_list_id ON items(list_id);

-- 5. Sessions Table (Session Persistency & Tokens)
CREATE TABLE IF NOT EXISTS sessions (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                          token VARCHAR(255) UNIQUE NOT NULL,
                          expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Index for session token validation lookup
CREATE INDEX IF NOT EXISTS idx_sessions_token ON sessions(token);
